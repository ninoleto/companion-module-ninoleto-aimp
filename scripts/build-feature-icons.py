def main() -> None:
    assets = ROOT / "assets" / "feature-icons"
    assets.mkdir(parents=True, exist_ok=True)
    result = {}
    with tempfile.TemporaryDirectory(prefix="aimp-feature-icon-") as temporary:
        for name, content in ICONS.items():
            source = assets / f"{name}.svg"
            source.write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" fill="none" stroke="#f1f5f9" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round">\n<!-- Original artwork. MIT license. -->\n' + content + '\n</svg>\n', encoding="utf-8")
            target = Path(temporary) / f"{name}.png"
            subprocess.run(["inkscape", str(source), "--export-type=png", "--export-width=144", "--export-height=144", "--export-background-opacity=0", f"--export-filename={target}"], check=True, capture_output=True)
            result[name] = "data:image/png;base64," + base64.b64encode(target.read_bytes()).decode("ascii")
    (ROOT / "src" / "feature-icons.js").write_text('// Generated by scripts/build-feature-icons.py. Original artwork: MIT license.\nexport const featureIcons = Object.freeze(' + json.dumps(result, indent=2) + ')\n', encoding="utf-8")
    print(f"Built {len(result)} original feature icons.")

if __name__ == "__main__":
    main()
