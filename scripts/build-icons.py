#!/usr/bin/env python3
"""Compile our MIT-licensed vector icons into runtime-free PNG data URIs.

Run: python3 scripts/build-icons.py
Requires either CairoSVG (pip install cairosvg) or the Inkscape CLI.
The generated module is committed; installing or running the module needs neither.
"""

from __future__ import annotations

import base64
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
try:
    import cairosvg
except ImportError:
    cairosvg = None


def render(source: Path) -> bytes:
    if cairosvg is not None:
        return cairosvg.svg2png(url=str(source), output_width=144, output_height=144)
    executable = shutil.which("inkscape")
    if executable is None:
        raise SystemExit("Install CairoSVG or Inkscape to rebuild the icons.")
    with tempfile.TemporaryDirectory(prefix="aimp-icon-") as scratch:
        target = Path(scratch) / "icon.png"
        subprocess.run(
            [executable, str(source), "--export-type=png", "--export-width=144",
             "--export-height=144", "--export-background-opacity=0",
             f"--export-filename={target}"],
            check=True, capture_output=True,
        )
        return target.read_bytes()


def main() -> None:
    icons = {}
    for source in sorted((ROOT / "assets" / "icons").glob("*.svg")):
        icons[source.stem] = "data:image/png;base64," + base64.b64encode(render(source)).decode("ascii")
    if not icons:
        raise SystemExit("No SVG icons found.")
    output = (
        "// Generated by scripts/build-icons.py. Original vector artwork: MIT license.\n"
        "// Transparent 144 × 144 PNGs; no runtime renderer or icon font required.\n"
        "export const iconImages = Object.freeze(" + json.dumps(icons, indent=2) + ")\n"
    )
    (ROOT / "src" / "preset-icons.js").write_text(output, encoding="utf-8")
    print(f"Built {len(icons)} icons in src/preset-icons.js")


if __name__ == "__main__":
    main()
